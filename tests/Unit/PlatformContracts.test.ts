import { describe, expect, it } from 'bun:test'
import { basename } from 'node:path'

async function files(pattern: string, cwd = import.meta.dir): Promise<string[]> {
  return Array.fromAsync(new Bun.Glob(pattern).scan({ cwd, absolute: true, onlyFiles: true }))
}

describe('tenant model contracts', () => {
  it('scopes every application model and generated API to Team', async () => {
    const modelFiles = await files('../../app/Models/*.ts')
    expect(modelFiles.length).toBeGreaterThanOrEqual(59)

    for (const file of modelFiles) {
      const source = await Bun.file(file).text()
      expect(source, `${basename(file)} must belong to Team`).toMatch(/belongsTo:\s*\[[^\]]*['"]Team['"]/s)
      expect(source, `${basename(file)} must protect API routes`).toContain("middleware: ['auth', 'team']")
    }
  })

  it('keeps schema changes model-generated', async () => {
    const sqliteMigrations = await files('../../database/migrations/*.sql')
    const postgresMigrations = await files('../../database/migrations/postgres/*.sql')
    const sqliteSnapshot = Bun.file(new URL('../../storage/framework/database/model-snapshot.sqlite.json', import.meta.url))
    const postgresSnapshot = Bun.file(new URL('../../storage/framework/database/model-snapshot.postgres.json', import.meta.url))

    expect(sqliteMigrations.length).toBeGreaterThan(250)
    expect(postgresMigrations.length).toBeGreaterThan(150)
    expect(await sqliteSnapshot.exists()).toBe(true)
    expect(await postgresSnapshot.exists()).toBe(true)

    for (const migration of postgresMigrations) {
      const source = await Bun.file(migration).text()
      // Newer generators put a `-- qb:generated` marker line above the header.
      expect(source, `${basename(migration)} must remain generator-owned`).toMatch(/^(?:-- qb:generated\n)?-- @generated by `buddy migrate:regenerate`/)
    }
  })
})

describe('interface contracts', () => {
  it('publishes a dedicated story for every feature in the navigation', async () => {
    const features = ['email', 'sms', 'publishing', 'forms', 'audience', 'automation', 'ai', 'deliverability', 'commerce', 'monetization', 'analytics', 'integrations']
    const navigation = await Bun.file(new URL('../../resources/components/CommsHQ/MarketingNavigation.stx', import.meta.url)).text()
    const stories = await Bun.file(new URL('../../resources/components/CommsHQ/FeatureStory.stx', import.meta.url)).text()

    // Assert the class is present, not the byte order of the attribute. This was a
    // literal match on `class="feature-menu group relative"` and it broke the day
    // pickier's sort-tailwind-classes rule was actually run on .stx files: the
    // linter and the test were pinning opposite orders of the same three classes.
    // A contract test should not care how a formatter arranges an attribute.
    expect(navigation).toMatch(/<details class="[^"]*\bfeature-menu\b[^"]*">/)
    expect(navigation).toContain('aria-label="Primary navigation"')
    expect(navigation).toContain('Explore the complete platform')

    for (const feature of features) {
      const page = await Bun.file(new URL(`../../resources/views/${feature}.stx`, import.meta.url)).text()
      expect(navigation, `${feature} must be linked from the feature menu`).toContain(`href: '/${feature}'`)
      expect(stories, `${feature} must have a substantive feature story`).toContain(`  ${feature}: {`)
      expect(page, `${feature} must render its dedicated story`).toContain(`<FeatureStory feature="${feature}" />`)
    }
  })

  it('ships every primary product page through the shared state-rich surface', async () => {
    // `segments` left this list when it started reading `/api/v1/segments`.
    // The surface holds its figures as literals, so a page stays on it only
    // until it has an endpoint to read; the pages still here are the ones
    // that have not been wired yet, not the ones that should stay.
    const required = ['sites', 'commerce']
    for (const page of required) {
      const source = await Bun.file(new URL(`../../resources/views/dashboard/commshq/${page}.stx`, import.meta.url)).text()
      expect(source).toContain(`<WorkspaceSurface area="${page}" />`)
    }

    const segments = await Bun.file(new URL('../../resources/views/dashboard/commshq/segments.stx', import.meta.url)).text()
    expect(segments).toContain('<SegmentsWorkspace />')
    expect(segments).not.toContain('<WorkspaceSurface')

    // `editor` followed, reading `/api/v1/message-templates`.
    const editor = await Bun.file(new URL('../../resources/views/dashboard/commshq/editor.stx', import.meta.url)).text()
    expect(editor).toContain('<MessageStudio />')
    expect(editor).not.toContain('<WorkspaceSurface')

    // `billing` followed, reading `/api/v1/usage-meters` and `/api/v1/subscriptions`.
    const billing = await Bun.file(new URL('../../resources/views/dashboard/commshq/billing.stx', import.meta.url)).text()
    expect(billing).toContain('<BillingWorkspace />')
    expect(billing).not.toContain('<WorkspaceSurface')

    // `reputation` followed, reading and acting through the reputation routes.
    const reputation = await Bun.file(new URL('../../resources/views/dashboard/commshq/reputation.stx', import.meta.url)).text()
    expect(reputation).toContain('<ReputationWorkspace />')
    expect(reputation).not.toContain('<WorkspaceSurface')

    // `forms` followed, reading and writing `/api/v1/forms`.
    const forms = await Bun.file(new URL('../../resources/views/dashboard/commshq/forms.stx', import.meta.url)).text()
    expect(forms).toContain('<FormsWorkspace />')
    expect(forms).not.toContain('<WorkspaceSurface')

    // `domains` and `senders` followed together, on the sending routes in
    // `routes/api.ts`: a sender is verified only through its domain.
    // `integrations` after them, storing credentials through its own actions.
    for (const [page, component] of [['domains', 'DomainsWorkspace'], ['senders', 'SendersWorkspace'], ['integrations', 'IntegrationsWorkspace'], ['publications', 'PublicationsWorkspace'], ['teams', 'TeamsWorkspace'], ['onboarding', 'SetupWorkspace'], ['settings', 'SettingsWorkspace'], ['monetization', 'MonetizationWorkspace'], ['analytics', 'AnalyticsWorkspace']] as const) {
      const view = await Bun.file(new URL(`../../resources/views/dashboard/commshq/${page}.stx`, import.meta.url)).text()
      expect(view).toContain(`<${component} />`)
      expect(view).not.toContain('<WorkspaceSurface')
    }

    // `campaigns` was never on the surface: it was a static composer of its
    // own. It reads `/api/campaigns` now, and its sample draft is gone.
    const campaigns = await Bun.file(new URL('../../resources/views/dashboard/commshq/campaigns.stx', import.meta.url)).text()
    const composer = await Bun.file(new URL('../../resources/components/CommsHQ/CampaignComposer.stx', import.meta.url)).text()
    expect(campaigns).toContain('<CampaignComposer />')
    expect(composer).toContain('campaignsUrl(')
    // Headings of the old static panels. The component's own comment names
    // the sample figures it replaced, so those are not what to look for.
    expect(composer).not.toContain('Campaign checks')
    expect(composer).not.toContain('Best send window')

    // `automations` was a static builder of its own too. It reads
    // `/api/automations` now, and it offers no way to switch one on.
    const automations = await Bun.file(new URL('../../resources/views/dashboard/commshq/automations.stx', import.meta.url)).text()
    const builder = await Bun.file(new URL('../../resources/components/CommsHQ/AutomationBuilder.stx', import.meta.url)).text()
    expect(automations).toContain('<AutomationBuilder />')
    expect(builder).toContain('automationsUrl(')
    expect(builder).not.toContain('Step inspector')
    expect(builder).not.toContain('Publish version')
    expect(builder).not.toMatch(/setStatus\([^)]*'active'\)/)

    const surface = await Bun.file(new URL('../../resources/components/CommsHQ/WorkspaceSurface.stx', import.meta.url)).text()
    for (const state of ['populated', 'loading', 'empty', 'error']) expect(surface).toContain(`'${state}'`)
  })

  it('publishes a footer-linked comparison page for every competitor', async () => {
    const competitors = ['mailchimp', 'klaviyo', 'kit', 'beehiiv', 'substack', 'birdeye', 'podium', 'hubspot', 'activecampaign', 'brevo', 'customer-io']
    const layout = await Bun.file(new URL('../../resources/views/layouts/marketing.stx', import.meta.url)).text()
    const comparisons = await Bun.file(new URL('../../resources/components/CommsHQ/CompetitorComparison.stx', import.meta.url)).text()
    const index = await Bun.file(new URL('../../resources/views/compare.stx', import.meta.url)).text()

    expect(layout, 'the footer must carry a Compare section').toContain('>Compare<')
    // href= or to=: the contract is that the footer links to the comparison
    // index, not which attribute spells it. Internal destinations are
    // <StxLink to="…"> per AGENTS.md, and StxLink still server-renders a
    // crawlable <a href="…">, so the destination is what this should assert.
    expect(layout).toMatch(/(?:href|to)="\/compare"/)

    for (const competitor of competitors) {
      const page = await Bun.file(new URL(`../../resources/views/compare/${competitor}.stx`, import.meta.url)).text()
      expect(page).toContain(`<CompetitorComparison competitor="${competitor}" />`)
      expect(page).toContain("@extends('marketing')")
      expect(layout, `${competitor} must be reachable from the footer`).toMatch(new RegExp(`(?:href|to)="/compare/${competitor}"`))
      expect(index, `${competitor} must be listed on the compare index`).toContain(`href: '/compare/${competitor}'`)
      expect(comparisons, `${competitor} must have comparison content`).toContain(`  ${competitor.includes('-') ? `'${competitor}'` : competitor}: {`)
    }
  })

  it('keeps every comparison fair and checkable', async () => {
    const source = await Bun.file(new URL('../../resources/components/CommsHQ/CompetitorComparison.stx', import.meta.url)).text()
    // Each entry concedes strengths, says when to pick the other product, and
    // links out so a reader can verify the claims for themselves.
    expect(source.match(/strengths: \[/g) ?? []).toHaveLength(11)
    expect(source.match(/chooseRival: '/g) ?? []).toHaveLength(11)
    expect(source.match(/verify: 'https:\/\//g) ?? []).toHaveLength(11)
    expect(source).toContain('Reviewed {{ REVIEWED }}')
  })

  it('ships the public consent completion destinations', async () => {
    for (const page of ['subscription-confirmed', 'preferences-saved']) {
      const source = await Bun.file(new URL(`../../resources/views/${page}.stx`, import.meta.url)).text()
      expect(source).toContain("@extends('marketing')")
      expect(source).toContain('focus-visible:outline')
    }
  })

  it('rejects browser scripting, hand-drawn icons, and forbidden punctuation in product STX', async () => {
    const resourceFiles = await files('../../resources/**/*.stx')
    for (const file of resourceFiles) {
      const source = await Bun.file(file).text()
      expect(source, `${basename(file)} contains forbidden punctuation`).not.toMatch(/[—–]/)
      expect(source, `${basename(file)} contains direct browser scripting`).not.toMatch(/\b(?:window|document)\s*\./)
      expect(source, `${basename(file)} contains a hand-drawn SVG`).not.toMatch(/<svg\b/i)
    }
  })
})
